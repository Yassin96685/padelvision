// ── Context ───────────────────────────────────────────────────────────────────

type LocaleContextType = {
  locale: LocaleCode;
  setLocale: (code: LocaleCode) => void;
  t: (key: string, args?: Record<string, string | number>) => string;
  localeReady: boolean;
  localeChosen: boolean;
};

const LocaleContext = createContext<LocaleContextType>({
  locale: 'en',
  setLocale: () => {},
  t: (key) => key,
  localeReady: false,
  localeChosen: false,
});

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<LocaleCode>('en');
  const [localeReady, setLocaleReady] = useState(false);
  const [localeChosen, setLocaleChosen] = useState(false);

  useEffect(() => {
    AsyncStorage.getItem(LOCALE_KEY)
      .then(stored => {
        if (stored === 'en' || stored === 'de' || stored === 'es' || stored === 'fr') {
          setLocaleState(stored);
          setLocaleChosen(true);
        }
      })
      .catch(() => {})
      .finally(() => setLocaleReady(true));
  }, []);

  const setLocale = useCallback((code: LocaleCode) => {
    setLocaleState(code);
    setLocaleChosen(true);
    AsyncStorage.setItem(LOCALE_KEY, code).catch(() => {});
  }, []);

  const t = useCallback((key: string, args?: Record<string, string | number>): string => {
    let str = ALL[locale][key] ?? ALL.en[key] ?? key;
    if (args) {
      Object.entries(args).forEach(([k, v]) => {
        str = str.replace(`{${k}}`, String(v));
      });
    }
    return str;
  }, [locale]);

  return (
    <LocaleContext.Provider value={{ locale, setLocale, t, localeReady, localeChosen }}>
      {children}
    </LocaleContext.Provider>
  );
}

export const useLocale = () => useContext(LocaleContext);
